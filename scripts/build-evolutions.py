"""Bundle the current PokeAPI evolution catalogue (ordinary evolutions only).

Usage: python scripts/build-evolutions.py [--data-dir DIRECTORY]
Without --data-dir, downloads the public CSV sources into a temporary directory.
The generated file records source hashes, so a snapshot can be identified later.
"""
import argparse
import csv
import hashlib
import json
import tempfile
import urllib.request
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = 'https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv/'
FILES = ['pokemon_evolution', 'pokemon_species', 'pokemon_species_names',
         'pokemon', 'pokemon_forms', 'pokemon_form_names', 'items', 'item_names', 'evolution_triggers']
# Pseudo-legendary final evolutions (base stat total 600 in the main series).
SEMI_LEGENDARY_SPECIES = {149, 248, 373, 376, 445, 635, 706, 784, 887, 998}


def build(directory):
    def rows(name):
        with (directory / (name + '.csv')).open(encoding='utf-8', newline='') as file:
            return list(csv.DictReader(file))

    species = {int(r['id']): r for r in rows('pokemon_species')}
    french = {int(r['pokemon_species_id']): r['name'] for r in rows('pokemon_species_names') if r['local_language_id'] == '5'}
    pokemon = {int(r['id']): r for r in rows('pokemon')}
    form_names = {int(r['pokemon_form_id']): r for r in rows('pokemon_form_names') if r['local_language_id'] == '5'}
    forms = {}
    defaults = {}
    for r in rows('pokemon_forms'):
        p = pokemon[int(r['pokemon_id'])]
        if r['is_mega'] == '1' or r['is_battle_only'] == '1' or '-gmax' in r['identifier'] or '-mega' in r['identifier']:
            continue
        fid, pid, sid = int(r['id']), int(p['id']), int(p['species_id'])
        forms[fid] = {'id': fid, 'pokemonId': pid, 'speciesId': sid, 'name': r['identifier'], 'formName': r['form_identifier']}
        if fid in form_names and form_names[fid]['pokemon_name']:
            forms[fid]['label'] = form_names[fid]['pokemon_name']
        if r['is_default'] == '1':
            defaults[pid] = fid

    items = {int(r['id']): r['identifier'] for r in rows('items')}
    item_names = {items[int(r['item_id'])]: r['name'] for r in rows('item_names') if r['local_language_id'] == '5'}
    triggers = {int(r['id']): r['identifier'] for r in rows('evolution_triggers')}
    rules = []
    for r in rows('pokemon_evolution'):
        if r['is_default'] != '1':
            continue  # Current canonical alternatives; historical methods are not stacked.
        sid = int(r['evolved_species_id'])
        parent = species[sid]['evolves_from_species_id']
        if not parent:
            continue
        source_form = int(r['required_pokemon_form_id'] or 0)
        target_form = int(r['evolved_pokemon_form_id'] or 0)
        if (source_form and source_form not in forms) or (target_form and target_form not in forms):
            continue
        rule = {'id': int(r['id']), 'from': int(parent), 'to': sid, 'trigger': triggers[int(r['evolution_trigger_id'])]}
        for key, value in r.items():
            if key in ('id', 'evolved_species_id', 'evolution_trigger_id', 'version_group_id', 'is_default') or value == '':
                continue
            if key in ('trigger_item_id', 'held_item_id'):
                rule[key] = items[int(value)]
            elif key in ('condition_expression', 'time_of_day'):
                rule[key] = value
            else:
                number = int(value)
                if number or key == 'relative_physical_stats':
                    rule[key] = number
        rules.append(rule)

    result = {
        'version': 1, 'retrievedAt': date.today().isoformat(), 'source': BASE,
        'sourceHashes': {f: hashlib.sha256((directory / (f + '.csv')).read_bytes()).hexdigest() for f in FILES},
        'species': {sid: {'name': r['identifier'], 'label': french.get(sid, r['identifier']),
                         'genderRate': int(r['gender_rate']), 'captureRate': int(r['capture_rate']),
                         'isLegendary': r['is_legendary'] == '1', 'isMythical': r['is_mythical'] == '1',
                         'isSemiLegendary': sid in SEMI_LEGENDARY_SPECIES} for sid, r in species.items()},
        'forms': forms, 'defaultForms': defaults, 'itemNames': item_names, 'rules': rules,
    }
    target = ROOT / 'media/evolution-data.js'
    target.write_text('// Generated by scripts/build-evolutions.py from PokeAPI.\n'
                      'window.POKEIDLE_EVOLUTION_DATA = ' + json.dumps(result, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
    print(f'{len(rules)} règles, {len(set(r["to"] for r in rules))} espèces évoluées : {target}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--data-dir', type=Path)
    args = parser.parse_args()
    if args.data_dir:
        build(args.data_dir)
    else:
        with tempfile.TemporaryDirectory(prefix='pokeidle-evolutions-') as temp:
            directory = Path(temp)
            for name in FILES:
                urllib.request.urlretrieve(BASE + name + '.csv', directory / (name + '.csv'))
            build(directory)
