const fs = require('node:fs');
const path = require('node:path');
const https = require('node:https');

const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'media/main.js'), 'utf8');
const mappingBlock = source.match(/const itemIconMapping = (\{[\s\S]*?\n    \});/)[1];
const mapping = Object.fromEntries([...mappingBlock.matchAll(/'([^']+)': '([^']+)'/g)].map((entry) => [entry[1], entry[2]]));
const ballsBlock = source.slice(source.indexOf('const BALL_TYPES'), source.indexOf('function getPokeDollarIcon'));
const challengeSource = fs.readFileSync(path.join(root, 'media/challenges.js'), 'utf8');
const itemCatalog = JSON.parse(challengeSource.match(/\/\* POKEIDLE_ITEMS_START \*\/\s*const items = ([\s\S]*?);\s*\/\* POKEIDLE_ITEMS_END \*\//)[1]);
const ids = [...new Set([
  ...[...ballsBlock.matchAll(/img: '([^']+)'/g)].map((entry) => entry[1]),
  ...itemCatalog.map((item) => mapping[item.id] || item.id),
  ...Object.values(mapping), 'rare-candy', 'gracidea'
])].sort();
const icons = {};
function download(id) {
  if (!/^[a-z0-9-]+$/.test(id)) throw new Error('Identifiant d’icône invalide.');
  return new Promise((resolve, reject) => {
    const request = https.get(`https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/items/${id}.png`, (response) => {
      if (response.statusCode !== 200) { response.resume(); reject(new Error(`${id}: HTTP ${response.statusCode}`)); return; }
      const chunks = []; let length = 0;
      response.on('data', (chunk) => {
        length += chunk.length;
        if (length > 128 * 1024) { request.destroy(new Error('Image trop volumineuse.')); return; }
        chunks.push(chunk);
      });
      response.on('error', reject);
      response.on('end', () => {
        const content = Buffer.concat(chunks);
        if (!content.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]))) { reject(new Error(`${id}: image PNG invalide.`)); return; }
        icons[id] = 'data:image/png;base64,' + content.toString('base64'); resolve();
      });
    });
    request.setTimeout(20000, () => request.destroy(new Error(`Chargement impossible : ${id}`)));
    request.on('error', reject);
  });
}
async function main() {
  let next = 0;
  await Promise.all(Array.from({ length: 6 }, async () => { while (next < ids.length) { const id = ids[next++]; await download(id); } }));
  const fallback = '<svg xmlns="http://www.w3.org/2000/svg" width="32" height="32" viewBox="0 0 32 32"><rect x="5" y="7" width="22" height="21" rx="4" fill="#7469ad" stroke="#ece9ff" stroke-width="2"/><path d="M11 8V6a5 5 0 0 1 10 0v2" fill="none" stroke="#ece9ff" stroke-width="2"/><path d="M12 17h8m-4-4v8" stroke="#ece9ff" stroke-width="2"/></svg>';
  icons.__fallback = 'data:image/svg+xml;base64,' + Buffer.from(fallback).toString('base64');
  const ordered = Object.fromEntries(Object.keys(icons).sort().map((key) => [key, icons[key]]));
  const destination = path.join(root, 'media/item-icons.js');
  fs.writeFileSync(destination, '// Bundled PokeAPI item sprites: https://github.com/PokeAPI/sprites\n// Generated by scripts/build-item-icons.cjs. No runtime download for these icons.\nwindow.POKEIDLE_ITEM_ICONS = Object.freeze(' + JSON.stringify(ordered) + ');\n');
  console.log(`${ids.length} icônes intégrées dans ${destination}`);
}
main().catch((error) => { console.error(error.message); process.exitCode = 1; });
